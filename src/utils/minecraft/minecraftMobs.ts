/**
 * Check if a name is a known Minecraft mob or non-player term (case-insensitive)
 */
export function isMinecraftMob(name: string): boolean {
	if (!name) return false;
	const clean = name.toLowerCase().trim();
	return MINECRAFT_MOBS.has(clean) || NON_PLAYER_KEYWORDS.has(clean);
}
